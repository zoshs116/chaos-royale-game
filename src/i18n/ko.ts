export function unitName(unitKey: string) {
    return UNIT_NAME_KO[unitKey] ?? unitKey;
}

export function fitKoreanText(text: string, maxLength: number) {
    if (text.length <= maxLength) return text;
    return `${text.slice(0, Math.max(1, maxLength - 1))}.`;
}

export function fitUnitNameKo(unitKey: string, maxLength = 7) {
    return fitKoreanText(unitName(unitKey), maxLength);
}
