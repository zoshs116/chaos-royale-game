import type { UnitStats } from '../entities/Unit';

/** 역할군 타입 */
export type UnitRole = 'tank' | 'assassin' | 'mage' | 'support' | 'siege' | 'swarm';

/** 진영 타입 */
export type Faction = 'sentinel' | 'scourge' | 'neutral';

/** 역할 카테고리 (가이드 기반) */
export type UnitCategory = 'tank' | 'magic' | 'assassin' | 'dealer' | 'summon' | 'terror';

/** 스킬 타입 */
export type SkillType =
    | 'none'
    | 'defense_aura'     // Stone Cold: 주변 아군 피해 감소
    | 'stun_hit'         // Muradin: N번째 공격 기절
    | 'sprint_ambush'    // Raiden: 스폰 시 이속 2배 + 첫 공격 2배
    | 'poison_dot'       // Viper: 공격 시 독 DoT
    | 'fire_zone'        // Agamemnon: 광역 화염지대
    | 'petrify'          // Medusa: N번째 공격 석화
    | 'lifesteal'        // Akasha: 데미지의 일부 회복
    | 'death_curse'      // Voodoo: 사망 시 주변 감속
    | 'siege_mode'       // Demolisher: 건물 공격 보너스
    | 'death_explode';   // Ghoul: 사망 시 폭발

export interface SkillParams {
    /** defense_aura: 피해 감소 비율 (0.15 = 15%) */
    damageReduction?: number;
    /** defense_aura: 오라 반경 */
    auraRadius?: number;
    /** stun_hit / petrify: 몇 번째 공격마다 */
    hitInterval?: number;
    /** stun_hit: 기절 지속 시간 (ms) */
    stunDuration?: number;
    /** petrify: 석화 지속 시간 (ms) */
    petrifyDuration?: number;
    /** sprint_ambush: 이속 배율 */
    speedMultiplier?: number;
    /** sprint_ambush: 지속 시간 (ms) */
    sprintDuration?: number;
    /** sprint_ambush: 첫 공격 데미지 배율 */
    firstHitMultiplier?: number;
    /** poison_dot: 초당 데미지 */
    dotDamagePerSec?: number;
    /** poison_dot: 지속 시간 (ms) */
    dotDuration?: number;
    /** fire_zone: 지면 화염 지속 시간 (ms) */
    fireZoneDuration?: number;
    /** fire_zone: 화염 범위 */
    fireZoneRadius?: number;
    /** fire_zone: 화염 초당 데미지 */
    fireZoneDps?: number;
    /** lifesteal: 흡수 비율 */
    lifestealRatio?: number;
    /** death_curse: 감속 비율 */
    slowRatio?: number;
    /** death_curse: 감속 범위 */
    curseRadius?: number;
    /** death_curse: 감속 지속 시간 (ms) */
    curseDuration?: number;
    /** siege_mode: 건물 보너스 데미지 비율 */
    siegeBonus?: number;
    /** death_explode: 폭발 데미지 */
    explodeDamage?: number;
    /** death_explode: 폭발 범위 */
    explodeRadius?: number;
}

export interface UnitData extends UnitStats {
    cost: number;
    name: string;
    description: string;
    spriteKey: string;
    role: UnitRole;
    faction?: Faction;
    category?: UnitCategory;
    isHidden?: boolean;
    skill: SkillType;
    skillParams: SkillParams;
}

